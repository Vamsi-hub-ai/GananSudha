/**
 * Automatically translates a product or category string into natural Telugu
 */
export function autoTranslateToTelugu(text) {
  if (!text || typeof text !== 'string') return text || '';
  let result = text;
  for (const [pattern, replacement] of VEDIC_TERM_REPLACEMENTS) {
    result = result.replace(pattern, replacement);
  }
  return result;
}

/**
 * Intelligent dynamic content resolver:
 * 1. Checks if object already has native Telugu field (`name_te`, `desc_te`, `description_te`, `title_te`)
 * 2. Checks local dynamic dictionary (Products, Categories, Services, Variants) by itemName or baseVal
 * 3. Uses Smart Vedic Term Replacer so ANY NEW ITEM added by admin shows in Telugu
 * 4. Falls back to original English content if language is not Telugu
 */
export function getTranslatedContent(itemOrText, field = 'name', language = 'en') {
  if (!itemOrText) return '';

  // If language is English, return directly
  if (language !== 'te') {
    if (typeof itemOrText === 'string') return itemOrText;
    return itemOrText[field] || itemOrText.name || itemOrText.title || '';
  }

  // Language is Telugu
  if (typeof itemOrText === 'object') {
    // 1. Direct explicit property check: name_te, desc_te, title_te, etc.
    const teField = `${field}_te`;
    if (itemOrText[teField]) return itemOrText[teField];
    if ((field === 'desc' || field === 'description') && itemOrText.desc_te) return itemOrText.desc_te;
    if ((field === 'desc' || field === 'description') && itemOrText.description_te) return itemOrText.description_te;
    if ((field === 'name' || field === 'title') && itemOrText.name_te) return itemOrText.name_te;
    if ((field === 'name' || field === 'title') && itemOrText.title_te) return itemOrText.title_te;

    const itemName = (itemOrText.name || itemOrText.title || '').trim();
    const rawVal = itemOrText[field] !== undefined ? itemOrText[field] : (itemOrText.name || itemOrText.title || '');
    const baseVal = (typeof rawVal === 'string' ? rawVal : '').trim();

    // 2. Exact products dictionary (Lookup by itemName or baseVal)
    const productEntry = DYNAMIC_TERMS.products[itemName] || DYNAMIC_TERMS.products[baseVal];
    if (productEntry) {
      if (field === 'desc' || field === 'description') {
        if (productEntry.desc) return productEntry.desc;
      }
      if (productEntry.name) return productEntry.name;
    }

    // 3. Exact services dictionary (Lookup by itemName or baseVal)
    const serviceName = itemName || baseVal;
    if (DYNAMIC_TERMS.services[serviceName]) {
      if (field === 'desc' || field === 'description') {
        if (DYNAMIC_TERMS.serviceDescriptions && DYNAMIC_TERMS.serviceDescriptions[serviceName]) {
          return DYNAMIC_TERMS.serviceDescriptions[serviceName];
        }
      }
      return DYNAMIC_TERMS.services[serviceName];
    }

    // 3b. Exact videos dictionary (Lookup by itemName or baseVal)
    const videoEntry = DYNAMIC_TERMS.videos[itemName] || DYNAMIC_TERMS.videos[baseVal];
    if (videoEntry) {
      if (field === 'desc' || field === 'description') {
        if (videoEntry.desc) return videoEntry.desc;
      }
      if (videoEntry.title || videoEntry.name) return videoEntry.title || videoEntry.name;
    }

    // 4. Categories dictionary
    if (DYNAMIC_TERMS.categories[itemName]) return DYNAMIC_TERMS.categories[itemName];
    if (DYNAMIC_TERMS.categories[baseVal]) return DYNAMIC_TERMS.categories[baseVal];

    // 5. Variants dictionary
    if (DYNAMIC_TERMS.variants[baseVal]) return DYNAMIC_TERMS.variants[baseVal];
    if (DYNAMIC_TERMS.variants[itemName]) return DYNAMIC_TERMS.variants[itemName];

    // 6. Automated smart keyword translation for newly added items
    const smartTranslated = autoTranslateToTelugu(baseVal);
    if (smartTranslated && smartTranslated !== baseVal) {
      return smartTranslated;
    }

    return baseVal || itemName;
  }

  // String lookup
  if (typeof itemOrText === 'string') {
    const trimmed = itemOrText.trim();
    if (DYNAMIC_TERMS.categories[trimmed]) return DYNAMIC_TERMS.categories[trimmed];
    if (DYNAMIC_TERMS.services[trimmed]) return DYNAMIC_TERMS.services[trimmed];
    if (DYNAMIC_TERMS.products[trimmed]) {
      if (field === 'desc' || field === 'description') {
        return DYNAMIC_TERMS.products[trimmed].desc || DYNAMIC_TERMS.products[trimmed].name;
      }
      return DYNAMIC_TERMS.products[trimmed].name;
    }
    if (DYNAMIC_TERMS.variants[trimmed]) return DYNAMIC_TERMS.variants[trimmed];

    // Smart fallback
    const smart = autoTranslateToTelugu(trimmed);
    return smart || trimmed;
  }

  return itemOrText;
}
